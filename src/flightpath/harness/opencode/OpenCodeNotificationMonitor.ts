import * as path from "path";
import {
  INotificationMonitor,
  HookConfig,
  NotificationMonitorBase,
} from "../shared/interfaces/INotificationMonitor";

/**
 * OpenCode CLI Notification Monitor
 *
 * Completion detection strategy: OpenCode TypeScript plugin system.
 *
 * Before the TUI launches, OpenCodeCliProvider writes a CommonJS plugin to
 * .opencode/plugin/flightpath-completion-hook.js. The plugin listens for
 * session.created and session.status idle events, then writes:
 *
 *   {sessionId}-start.json → on session.created (for early session ID capture)
 *   {sessionId}-stop.json  → on session.status idle (for completion detection)
 *
 * These match the standardized two-file format used by Claude and Copilot harnesses,
 * so all monitoring logic is inherited from NotificationMonitorBase unchanged.
 *
 * buildHookConfig() returns type: "none" because plugin file management is done
 * as a side effect in OpenCodeCliProvider.buildCliArgs() — not via CLI args.
 *
 * getPluginContent(notifyDir) is an opencode-specific method called directly
 * by OpenCodeCliProvider to get the plugin JS content to write to disk.
 */
export class OpenCodeNotificationMonitor
  extends NotificationMonitorBase
  implements INotificationMonitor
{
  /**
   * Build hook configuration.
   *
   * Returns type: "none" — OpenCode completion detection uses a plugin file
   * written to .opencode/plugin/ before execution, not CLI arguments.
   */
  buildHookConfig(
    scriptPath: string,
    notifyDir: string,
    workspaceRoot: string
  ): HookConfig {
    return { type: "none" };
  }

  /**
   * Get notification directory for OpenCode
   */
  getNotificationDirectory(workspaceRoot: string): string {
    return path.join(
      workspaceRoot,
      ".flightpath",
      "temp",
      "opencode-notifications"
    );
  }

  /**
   * Get the plugin JS content with the notify directory path substituted.
   *
   * Called by OpenCodeCliProvider.buildCliArgs() to get the content to write
   * to .opencode/plugin/flightpath-completion-hook.js before launching.
   *
   * The plugin:
   * - Tracks main sessions (no parentID) via session.created events
   * - Writes {sessionId}-start.json on session.created for early session ID capture
   * - Writes {sessionId}-stop.json on session.status idle for completion detection
   * - Filters child sessions (multi-agent subagents) to avoid false positives
   *
   * @param notifyDir Absolute path to the notification directory
   * @returns CommonJS plugin source code
   */
  getPluginContent(notifyDir: string): string {
    // Normalize to forward slashes for cross-platform safety
    const normalizedNotifyDir = notifyDir.replace(/\\/g, "/");

    return `// Auto-generated by FlightPath — do not edit
const { writeFileSync, mkdirSync } = require("fs");
const NOTIFY_DIR = "${normalizedNotifyDir}";
const mainSessions = new Set();

exports.FlightPathHook = async ({ client }) => {
  return {
    event: async ({ event }) => {
      if (event.type === "session.created") {
        const session = event.properties.info;
        if (!session.parentID) {
          mainSessions.add(session.id);
          try {
            mkdirSync(NOTIFY_DIR, { recursive: true });
            writeFileSync(
              \`\${NOTIFY_DIR}/\${session.id}-start.json\`,
              JSON.stringify({
                hookEvent: "SessionStart",
                sessionId: session.id,
                status: "started",
                timestamp: Date.now(),
              })
            );
          } catch (e) {
            /* ignore write errors */
          }
        }
      }
      if (event.type === "session.deleted") {
        mainSessions.delete(event.properties.info.id);
      }
      if (event.type === "session.status") {
        const { sessionID, status } = event.properties;
        if (status.type === "idle" && mainSessions.has(sessionID)) {
          try {
            mkdirSync(NOTIFY_DIR, { recursive: true });
            writeFileSync(
              \`\${NOTIFY_DIR}/\${sessionID}-stop.json\`,
              JSON.stringify({
                hookEvent: "Stop",
                sessionId: sessionID,
                status: "completed",
                timestamp: Date.now(),
              })
            );
          } catch (e) {
            /* ignore write errors */
          }
        }
      }
    },
  };
};
`;
  }
}
