import type { UserHookConfig } from "../../../types/FlightPathTypes";

/**
 * Generates the OpenCode completion hook plugin with user hook commands embedded.
 *
 * When no user hooks are provided, the generated output is functionally identical
 * to the static `flightpath-opencode-plugin.js` template. When user hooks are
 * present, stop/sessionStart commands are injected inline so the plugin runs
 * them after writing the corresponding notification file.
 */
export class OpenCodePluginGenerator {
  /**
   * Generate a plugin JS string.
   *
   * @param userHooks Optional array of user-defined hook configs
   * @returns CommonJS plugin source string
   */
  static generate(userHooks?: UserHookConfig[]): string {
    const stopCommands = (userHooks ?? [])
      .filter((h) => h.event === "stop")
      .map((h) => JSON.stringify(h.command));

    const startCommands = (userHooks ?? [])
      .filter((h) => h.event === "sessionStart")
      .map((h) => JSON.stringify(h.command));

    const userStopBlock =
      stopCommands.length > 0
        ? `
    // User-defined stop hooks from workflow
    const USER_STOP_HOOKS = [${stopCommands.join(", ")}];
    const { execSync: execSyncStop } = require("child_process");
    for (const cmd of USER_STOP_HOOKS) {
      try {
        execSyncStop(cmd, { stdio: "inherit", cwd: workspaceRoot || process.cwd() });
      } catch (e) {
        // User hook failure must not break completion detection
      }
    }`
        : "";

    const userStartBlock =
      startCommands.length > 0
        ? `
    // User-defined session start hooks from workflow
    const USER_START_HOOKS = [${startCommands.join(", ")}];
    const { execSync: execSyncStart } = require("child_process");
    for (const cmd of USER_START_HOOKS) {
      try {
        execSyncStart(cmd, { stdio: "inherit", cwd: workspaceRoot || process.cwd() });
      } catch (e) {
        // User hook failure must not break completion detection
      }
    }`
        : "";

    return `// FlightPath OpenCode Completion Hook Plugin (Generated)
// This file is auto-generated by FlightPath. Do not edit manually.
"use strict";

const fs = require("fs");
const path = require("path");

const mainSessions = new Set();
const notifyDir = process.env.FLIGHTPATH_NOTIFY_DIR;
const runId = process.env.FLIGHTPATH_RUN_ID;
const diagnosticLogs = process.env.FLIGHTPATH_DIAGNOSTIC_LOGS === "true";
const workspaceRoot = process.env.FLIGHTPATH_WORKSPACE_ROOT || process.cwd();

function _debugLog(message, data) {
  if (!diagnosticLogs) return;
  try {
    const logDir = path.join(workspaceRoot, ".flightpath", "logs");
    fs.mkdirSync(logDir, { recursive: true });
    const logFile = path.join(logDir, "flightpath-opencode-plugin-debug.log");
    const timestamp = new Date().toISOString();
    let logLine = \`[\${timestamp}] \${message}\`;
    if (data !== undefined) {
      logLine += \` \${JSON.stringify(data)}\`;
    }
    fs.appendFileSync(logFile, logLine + "\\n");
  } catch {
    // Silently swallow logging errors
  }
}

exports.FlightPathHook = function(hookContext) {
  if (!notifyDir) {
    _debugLog("FLIGHTPATH_NOTIFY_DIR not set — plugin inactive");
    return;
  }

  const { event, data } = hookContext;
  _debugLog("Event received", { event, sessionId: data?.sessionId, parentId: data?.parentID, status: data?.status });

  if (event === "session.created") {
    if (data?.parentID) {
      _debugLog("Ignoring child session", { sessionId: data.sessionId, parentID: data.parentID });
      return;
    }

    mainSessions.add(data.sessionId);
    _debugLog("Main session created", { sessionId: data.sessionId, mainSessionCount: mainSessions.size });

    const effectiveId = runId || data.sessionId;
    const startFile = path.join(notifyDir, \`\${effectiveId}-start.json\`);
    const payload = JSON.stringify({
      hookEvent: "SessionStart",
      sessionId: data.sessionId,
      timestamp: Date.now(),
      runId: runId || undefined,
    });

    try {
      fs.mkdirSync(notifyDir, { recursive: true });
      fs.writeFileSync(startFile, payload);
      _debugLog("Start notification written", { path: startFile });
    } catch (err) {
      _debugLog("Failed to write start notification", { error: String(err) });
    }
${userStartBlock}
  } else if (event === "session.deleted") {
    mainSessions.delete(data?.sessionId);
    _debugLog("Session deleted", { sessionId: data?.sessionId, mainSessionCount: mainSessions.size });
  } else if (event === "session.status" && data?.status === "idle") {
    if (!mainSessions.has(data?.sessionId)) {
      _debugLog("Ignoring idle for non-main session", { sessionId: data?.sessionId });
      return;
    }

    _debugLog("Main session idle — writing stop notification", { sessionId: data.sessionId });

    const stopFile = path.join(notifyDir, \`\${data.sessionId}-stop.json\`);
    const payload = JSON.stringify({
      hookEvent: "Stop",
      sessionId: data.sessionId,
      timestamp: Date.now(),
    });

    try {
      fs.mkdirSync(notifyDir, { recursive: true });
      fs.writeFileSync(stopFile, payload);
      _debugLog("Stop notification written", { path: stopFile });
    } catch (err) {
      _debugLog("Failed to write stop notification", { error: String(err) });
    }
${userStopBlock}
  }
};
`;
  }
}
