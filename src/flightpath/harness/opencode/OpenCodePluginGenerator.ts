import type { UserHookConfig } from "../../../types/FlightPathTypes";

/**
 * Generates the OpenCode completion hook plugin with user hook commands embedded.
 *
 * The plugin is written as a TypeScript file (.ts) — OpenCode only loads .ts plugins,
 * not .js. The generated content uses ESM import/export syntax (not CommonJS require).
 *
 * Event support by mode:
 *   - stop (session.idle):        both interactive and headless ✓
 *   - sessionStart (session.created): NOT firing (known OpenCode bug #14808)
 *   - preToolUse/postToolUse:     interactive only (tool.execute.* not available in headless)
 *
 * Notification file writing (for FlightPath completion detection) is gated on
 * FLIGHTPATH_NOTIFY_DIR so the plugin can be deployed in headless mode without
 * a notify directory, while still firing user hook commands.
 *
 * When no user hooks are provided, the output is functionally identical to the
 * static flightpath-opencode-plugin.ts template.
 */
export class OpenCodePluginGenerator {
  /**
   * Generate a plugin TypeScript string.
   *
   * @param userHooks Optional array of user-defined hook configs
   * @returns ESM TypeScript plugin source string (write to .ts file)
   */
  static generate(userHooks?: UserHookConfig[]): string {
    const stopCommands = (userHooks ?? [])
      .filter((h) => h.event === "stop")
      .map((h) => JSON.stringify(h.command));

    const startCommands = (userHooks ?? [])
      .filter((h) => h.event === "sessionStart")
      .map((h) => JSON.stringify(h.command));

    const preToolCommands = (userHooks ?? [])
      .filter((h) => h.event === "preToolUse")
      .map((h) => JSON.stringify(h.command));

    const postToolCommands = (userHooks ?? [])
      .filter((h) => h.event === "postToolUse")
      .map((h) => JSON.stringify(h.command));

    // Only import execSync if there are any user hook commands to run
    const hasAnyHooks =
      stopCommands.length > 0 ||
      startCommands.length > 0 ||
      preToolCommands.length > 0 ||
      postToolCommands.length > 0;

    const execSyncImport = hasAnyHooks
      ? `import { execSync } from "child_process";`
      : "";

    const runHooks = (cmds: string[]) =>
      cmds.length === 0
        ? ""
        : `
          for (const cmd of [${cmds.join(", ")}]) {
            try { execSync(cmd, { stdio: "inherit", cwd: workspaceRoot }); } catch (_e) {}
          }`;

    const userStopBlock = runHooks(stopCommands);
    const userStartBlock = runHooks(startCommands);
    const preToolBlock = runHooks(preToolCommands);
    const postToolBlock = runHooks(postToolCommands);

    return `// FlightPath OpenCode Completion Hook Plugin (Generated)
// This file is auto-generated by FlightPath. Do not edit manually.
import { writeFileSync, mkdirSync, appendFileSync } from "fs";
import path from "path";
${execSyncImport}

const notifyDir: string | undefined = process.env.FLIGHTPATH_NOTIFY_DIR;
const runId: string | undefined = process.env.FLIGHTPATH_RUN_ID;
const workspaceRoot: string = process.env.FLIGHTPATH_WORKSPACE_ROOT || process.cwd();

// Diagnostic logging — only when notifyDir is set (interactive mode).
const _logsDir = notifyDir ? path.resolve(notifyDir, "..", "..", "logs") : null;
let _logPath: string | null = null;
try {
  if (process.env.FLIGHTPATH_DIAGNOSTIC_LOGS === "true" && _logsDir) {
    mkdirSync(_logsDir, { recursive: true });
    _logPath = path.join(_logsDir, "flightpath-opencode-plugin-debug.log");
  }
} catch (_e) {}

function _debugLog(message: string, data?: unknown): void {
  if (!_logPath) return;
  try {
    const ts = new Date().toISOString();
    let entry = \`[\${ts}] \${message}\`;
    if (data !== undefined && data !== null) entry += "\\n" + JSON.stringify(data, null, 2);
    appendFileSync(_logPath, entry + "\\n---\\n");
  } catch (_e) {}
}

export const FlightPathHook = async (_hookContext: unknown) => {
  _debugLog("🚀 FlightPath OpenCode plugin loaded (generated)", { notifyDir, runId, workspaceRoot });

  return {
    event: async ({ event }: { event: { type: string; properties: Record<string, unknown> } }) => {
      _debugLog("📥 Event received", { type: event.type });

      if (event.type === "session.created") {
        const session = event.properties.info as { id: string; parentID?: string };
        _debugLog("🔍 session.created", { sessionId: session.id, parentID: session.parentID ?? null });
        if (!session.parentID) {
          if (notifyDir) {
            try {
              mkdirSync(notifyDir, { recursive: true });
              const startName = runId || session.id;
              const startFile = \`\${notifyDir}/\${startName}-start.json\`;
              writeFileSync(startFile, JSON.stringify({ hookEvent: "SessionStart", sessionId: session.id, status: "started", timestamp: Date.now() }));
              _debugLog("✅ Wrote start file", { file: startFile });
            } catch (e) { _debugLog("❌ Failed to write start file", { error: String(e) }); }
          }
${userStartBlock}
        }

      } else if (event.type === "tool.execute.before") {
${preToolBlock}
      } else if (event.type === "tool.execute.after") {
${postToolBlock}
      } else if (event.type === "session.idle") {
        // session.idle fires when the session completes — no session-tracking needed.
        const { sessionID } = event.properties as { sessionID: string };
        _debugLog("🛑 session.idle", { sessionID });

        if (notifyDir) {
          try {
            mkdirSync(notifyDir, { recursive: true });
            const stopFile = \`\${notifyDir}/\${sessionID}-stop.json\`;
            writeFileSync(stopFile, JSON.stringify({ hookEvent: "Stop", sessionId: sessionID, status: "completed", timestamp: Date.now() }));
            _debugLog("✅ Wrote stop file", { file: stopFile, sessionID });
          } catch (e) { _debugLog("❌ Failed to write stop file", { error: String(e) }); }
        }
${userStopBlock}
      }
    },
  };
};
`;
  }
}
