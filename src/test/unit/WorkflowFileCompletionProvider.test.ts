import * as assert from "assert";
import { readFileSync } from "fs";
import * as os from "os";
import * as path from "path";
import { suite, test } from "mocha";
import * as vscode from "vscode";
import { WorkflowFileCompletionProvider } from "../../completions/WorkflowFileCompletionProvider";
import { HARNESS_IDS } from "../../types/DashboardConstants";
import {
  CLAUDE_CLI_MODEL_LABELS,
  COPILOT_CLI_MODEL_IDS,
} from "../../utils/ModelConstants";
import { PromptDocumentStub } from "../helpers/PromptDocumentStub";

type SchemaNode = Record<string, unknown>;

const schema = JSON.parse(
  readFileSync(
    path.resolve(__dirname, "../../../schemas/workflow-schema.json"),
    "utf8"
  )
) as SchemaNode;

function resolveReference(reference: string): SchemaNode {
  const node = reference
    .slice(2)
    .split("/")
    .map((part) => part.replace(/~1/g, "/").replace(/~0/g, "~"))
    .reduce<unknown>((current, part) => {
      if (typeof current !== "object" || current === null) return undefined;
      return (current as Record<string, unknown>)[part];
    }, schema);
  assert.ok(node && typeof node === "object", `schema reference ${reference}`);
  return node as SchemaNode;
}

/** A key the schema removed (`not: {}`, e.g. `returns`) accepts no value and is never offered. */
function isRemovedKey(node: SchemaNode): boolean {
  const resolved =
    typeof node.$ref === "string" ? resolveReference(node.$ref) : node;
  if (resolved !== node) return isRemovedKey(resolved);
  const not = resolved.not;
  return (
    typeof not === "object" && not !== null && Object.keys(not).length === 0
  );
}

function schemaPropertyKeys(
  definitionName: "promptStep" | "scriptStep"
): string[] {
  const definitions = schema.$defs as Record<string, SchemaNode>;
  const keys = new Set<string>();

  function collect(node: SchemaNode): void {
    if (typeof node.$ref === "string") {
      collect(resolveReference(node.$ref));
    }
    const properties = node.properties;
    if (typeof properties === "object" && properties !== null) {
      for (const [key, value] of Object.entries(properties)) {
        // Runtime metadata is generated by execution and is not an authoring key.
        if (key === "_runtime" || isRemovedKey(value as SchemaNode)) continue;
        keys.add(key);
      }
    }
    if (Array.isArray(node.allOf)) {
      for (const branch of node.allOf) {
        if (typeof branch === "object" && branch !== null) {
          collect(branch as SchemaNode);
        }
      }
    }
  }

  collect(definitions[definitionName]);
  return [...keys].sort();
}

const CURSOR = "§";

/** Completions at the `§` marker of a ctrlyoke file, or undefined when the provider declines. */
async function complete(
  fileName: string,
  marked: string,
  triggerCharacter?: string
): Promise<vscode.CompletionList | undefined> {
  const text = marked.replace(CURSOR, "");
  const document = new PromptDocumentStub(
    path.join(os.tmpdir(), "workflow-file-completion", fileName),
    fileName.endsWith(".json") ? "json" : "yaml",
    text
  );
  const position = document.positionAt(marked.indexOf(CURSOR));
  return new WorkflowFileCompletionProvider().provideCompletionItems(
    document.asDocument(),
    position,
    new vscode.CancellationTokenSource().token,
    {
      triggerKind: triggerCharacter
        ? vscode.CompletionTriggerKind.TriggerCharacter
        : vscode.CompletionTriggerKind.Invoke,
      triggerCharacter,
    }
  );
}

const labelOf = (item: vscode.CompletionItem): string =>
  typeof item.label === "string" ? item.label : item.label.label;

const labels = (list: vscode.CompletionList | undefined): string[] =>
  (list?.items ?? []).map(labelOf).sort();

suite("WorkflowFileCompletionProvider", () => {
  test("offers only prompt-step keys from the workflow schema", async () => {
    const offered = labels(
      await complete("w.ctrlyoke.yaml", "steps:\n  - prompt: hello\n    §")
    );
    const allowed = schemaPropertyKeys("promptStep");
    assert.ok(offered.includes("harness"));
    assert.ok(!offered.includes("prompt"), "an existing key is not offered");
    for (const key of offered) {
      assert.ok(allowed.includes(key), `${key} is not a prompt-step key`);
    }
  });

  test("offers only script-step keys for a script step", async () => {
    const offered = labels(
      await complete(
        "w.ctrlyoke.yaml",
        "steps:\n  - type: script\n    script: echo hello\n    §"
      )
    );
    const allowed = schemaPropertyKeys("scriptStep");
    assert.ok(offered.length > 0);
    for (const key of offered) {
      assert.ok(allowed.includes(key), `${key} is not a script-step key`);
    }
  });

  test("offers step keys for members of a parallel group", async () => {
    const offered = labels(
      await complete(
        "w.ctrlyoke.yaml",
        "steps:\n  - parallel:\n      - prompt: hi\n        §"
      )
    );
    assert.ok(offered.includes("resumeSession"));
  });

  test("replaces the partial key under the cursor", async () => {
    const list = await complete(
      "w.ctrlyoke.yaml",
      "steps:\n  - prompt: hi\n    har§"
    );
    const item = list?.items.find((entry) => labelOf(entry) === "harness");
    assert.ok(item?.range && "start" in item.range);
    assert.deepStrictEqual(
      [item.range.start.character, item.range.end.character],
      [4, 7]
    );
  });

  test("offers harness ids as values in YAML", async () => {
    const offered = labels(
      await complete(
        "w.ctrlyoke.yaml",
        "steps:\n  - prompt: hi\n    harness: §"
      )
    );
    for (const id of Object.values(HARNESS_IDS)) {
      assert.ok(offered.includes(id), `${id} should be offered`);
    }
  });

  test("offers the models of the step's own harness, not a fixed Copilot list", async () => {
    const offered = labels(
      await complete(
        "w.ctrlyoke.yaml",
        "steps:\n  - prompt: hi\n    harness: claude-cli\n    model: §"
      )
    );
    for (const id of Object.keys(CLAUDE_CLI_MODEL_LABELS)) {
      assert.ok(offered.includes(id), `${id} should be offered`);
    }
    assert.ok(
      !offered.includes(COPILOT_CLI_MODEL_IDS[0]),
      "a Copilot model is not offered for a Claude step"
    );
  });

  test("completes keys and values in JSON workflow files", async () => {
    const keys = await complete(
      "w.ctrlyoke.json",
      '{ "steps": [{ "prompt": "hi", "har§" }] }'
    );
    const harness = keys?.items.find((entry) => labelOf(entry) === "harness");
    assert.ok(harness, "harness key");
    assert.ok(String(harness.insertText).startsWith('"harness"'));

    const values = labels(
      await complete(
        "w.ctrlyoke.json",
        '{ "steps": [{ "prompt": "hi", "harness": "§" }] }'
      )
    );
    assert.ok(values.includes(HARNESS_IDS.CLAUDE_CLI));
  });

  test("filters JSON keys on the quoted text the replace range covers", async () => {
    const list = await complete(
      "w.ctrlyoke.json",
      '{ "steps": [{ "prompt": "hi", "har§" }] }'
    );
    const harness = list?.items.find((entry) => labelOf(entry) === "harness");
    assert.ok(
      harness?.filterText?.startsWith('"har'),
      String(harness?.filterText)
    );
  });

  test("inserts multi-line keys as is, already indented to the key", async () => {
    const list = await complete(
      "w.ctrlyoke.yaml",
      "steps:\n  - prompt: hi\n    sk§"
    );
    const skills = list?.items.find((entry) => labelOf(entry) === "skills");
    assert.ok(skills);
    assert.strictEqual(skills.keepWhitespace, true);
  });

  test("a typed space opens values but not a key list", async () => {
    assert.strictEqual(
      await complete(
        "w.ctrlyoke.json",
        '{ "steps": [{ "prompt": "x", § }] }',
        " "
      ),
      undefined
    );
    assert.ok(
      labels(
        await complete(
          "w.ctrlyoke.yaml",
          "steps:\n  - prompt: hi\n    harness: §",
          " "
        )
      ).includes(HARNESS_IDS.CLAUDE_CLI)
    );
  });

  test("completes frontmatter keys in a .prompt.md file", async () => {
    const offered = labels(
      await complete("review.prompt.md", "---\nna§\n---\nReview the diff")
    );
    assert.ok(offered.includes("description"));
  });

  test("offers nothing in prompt text, script text, comments or block scalars", async () => {
    for (const marked of [
      "steps:\n  - prompt: Summarize the diff and mo§",
      "steps:\n  - prompt: |\n      Summarize the diff and\n      mo§",
      "steps:\n  - type: script\n    script: echo hi§",
      "steps:\n  - type: script\n    script: |\n      echo hi\n      ti§",
      "# har§\nsteps:\n  - prompt: hi",
    ]) {
      assert.strictEqual(
        await complete("w.ctrlyoke.yaml", marked),
        undefined,
        marked
      );
    }
  });

  test("ignores files that are not ctrlyoke files", async () => {
    assert.strictEqual(
      await complete("plain.yaml", "steps:\n  - prompt: hi\n    §"),
      undefined
    );
  });
});
