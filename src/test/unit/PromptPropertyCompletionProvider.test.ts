import * as assert from "assert";
import { readFileSync } from "fs";
import * as path from "path";
import { suite, test } from "mocha";
import * as vscode from "vscode";
import { PromptPropertyCompletionProvider } from "../../completions/PromptPropertyCompletionProvider";

type SchemaNode = Record<string, unknown>;

const schema = JSON.parse(
  readFileSync(
    path.resolve(__dirname, "../../../schemas/workflow-schema.json"),
    "utf8"
  )
) as SchemaNode;

function resolveReference(reference: string): SchemaNode {
  const node = reference
    .slice(2)
    .split("/")
    .map((part) => part.replace(/~1/g, "/").replace(/~0/g, "~"))
    .reduce<unknown>((current, part) => {
      if (typeof current !== "object" || current === null) return undefined;
      return (current as Record<string, unknown>)[part];
    }, schema);
  assert.ok(node && typeof node === "object", `schema reference ${reference}`);
  return node as SchemaNode;
}

function schemaPropertyKeys(
  definitionName: "promptStep" | "scriptStep"
): string[] {
  const definitions = schema.$defs as Record<string, SchemaNode>;
  const keys = new Set<string>();

  function collect(node: SchemaNode): void {
    if (typeof node.$ref === "string") {
      collect(resolveReference(node.$ref));
    }
    const properties = node.properties;
    if (typeof properties === "object" && properties !== null) {
      for (const key of Object.keys(properties)) {
        // Runtime metadata is generated by execution and is not an authoring key.
        if (key !== "_runtime") keys.add(key);
      }
    }
    if (Array.isArray(node.allOf)) {
      for (const branch of node.allOf) {
        if (typeof branch === "object" && branch !== null) {
          collect(branch as SchemaNode);
        }
      }
    }
  }

  collect(definitions[definitionName]);
  return [...keys].sort();
}

async function offeredKeys(step: "prompt" | "script"): Promise<string[]> {
  const stepYaml =
    step === "prompt"
      ? "steps:\n  - prompt: hello\n    "
      : "steps:\n  - type: script\n    script: echo hello\n    ";
  const document = await vscode.workspace.openTextDocument({
    language: "yaml",
    content: stepYaml,
  });
  const provider = new PromptPropertyCompletionProvider();
  const tokenSource = new vscode.CancellationTokenSource();
  try {
    const result = await provider.provideCompletionItems(
      document,
      new vscode.Position(
        document.lineCount - 1,
        document.lineAt(document.lineCount - 1).text.length
      ),
      tokenSource.token,
      {
        triggerKind: vscode.CompletionTriggerKind.Invoke,
        triggerCharacter: undefined,
      }
    );
    assert.ok(result, `${step} step should receive key completions`);
    return result.items
      .map((item) =>
        typeof item.label === "string" ? item.label : item.label.label
      )
      .sort();
  } finally {
    tokenSource.dispose();
  }
}

suite("PromptPropertyCompletionProvider", () => {
  test("offers prompt-step keys from the workflow schema", async () => {
    assert.deepStrictEqual(
      await offeredKeys("prompt"),
      schemaPropertyKeys("promptStep")
    );
  });

  test("offers script-step keys from the workflow schema", async () => {
    assert.deepStrictEqual(
      await offeredKeys("script"),
      schemaPropertyKeys("scriptStep")
    );
  });
});
