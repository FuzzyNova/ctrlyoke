#!/usr/bin/env node

/**
 * Generate custom-icons.css from SVG files in src/ui/icons/
 *
 * This script:
 * 1. Reads all .svg files from icons directory
 * 2. Optimizes SVGs (removes fills/strokes to work with CSS mask)
 * 3. Converts to base64 data URIs
 * 4. Generates CSS classes like .icon-{name}
 * 5. Uses mask-image for currentColor inheritance (like codicons)
 *
 * Usage: node scripts/generate-custom-icons.mjs
 */

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const ICONS_DIR = path.join(__dirname, "..", "src", "ui", "icons");
const OUTPUT_FILE = path.join(
  __dirname,
  "..",
  "src",
  "ui",
  "webview",
  "custom-icons.css"
);

/**
 * Optimize SVG for CSS mask usage
 * Removes fill/stroke attributes so mask can apply currentColor
 */
function optimizeSvgForMask(svgContent) {
  let optimized = svgContent;

  // Remove XML declaration
  optimized = optimized.replace(/<\?xml[^?]*\?>/g, "");

  // Remove comments
  optimized = optimized.replace(/<!--[\s\S]*?-->/g, "");

  // Remove fills and strokes (mask will apply color via background-color)
  optimized = optimized.replace(/\s*fill="[^"]*"/g, "");
  optimized = optimized.replace(/\s*stroke="[^"]*"/g, "");

  // Ensure paths use fill (not stroke) for mask to work
  // If original was stroke-based, we need to keep stroke but remove color
  // For mask-image, black = opaque, transparent = cut out
  // So we want solid shapes

  // Remove newlines and extra whitespace
  optimized = optimized.replace(/\n/g, " ");
  optimized = optimized.replace(/\s+/g, " ");
  optimized = optimized.trim();

  return optimized;
}

/**
 * Convert SVG to base64 data URI
 */
function svgToDataUri(svgContent) {
  const optimized = optimizeSvgForMask(svgContent);
  const base64 = Buffer.from(optimized).toString("base64");
  return `data:image/svg+xml;base64,${base64}`;
}

/**
 * Generate icon class name from filename
 * Example: append-next.svg -> icon-append-next
 */
function getIconClassName(filename) {
  const name = path.basename(filename, ".svg");
  return `icon-${name}`;
}

/**
 * Main function
 */
function generateCustomIcons() {
  console.log("🎨 Generating custom icons CSS...\n");

  // Check if icons directory exists
  if (!fs.existsSync(ICONS_DIR)) {
    console.log("⚠️  No icons directory found at:", ICONS_DIR);
    console.log("Creating empty custom-icons.css");
    fs.writeFileSync(OUTPUT_FILE, "/* No custom icons found */\n");
    return;
  }

  // Read all SVG files
  const files = fs
    .readdirSync(ICONS_DIR)
    .filter((f) => f.endsWith(".svg"))
    .sort();

  if (files.length === 0) {
    console.log("⚠️  No SVG files found in:", ICONS_DIR);
    console.log("Creating empty custom-icons.css");
    fs.writeFileSync(OUTPUT_FILE, "/* No custom icons found */\n");
    return;
  }

  console.log(`Found ${files.length} icon(s):`);
  files.forEach((f) => console.log(`  - ${f}`));
  console.log();

  // Generate CSS
  let css = `/**
 * Custom Icons - Auto-generated from SVG files
 * 
 * DO NOT EDIT THIS FILE DIRECTLY
 * Edit SVG files in src/ui/webview/icons/ and run: npm run generate-icons
 * 
 * Generated: ${new Date().toISOString()}
 */

/* Base class for all custom icons */
.custom-icon {
  display: inline-block;
  width: 16px;
  height: 16px;
  vertical-align: text-bottom;
  background-color: currentColor;
  -webkit-mask-size: contain;
  mask-size: contain;
  -webkit-mask-repeat: no-repeat;
  mask-repeat: no-repeat;
  -webkit-mask-position: center;
  mask-position: center;
}

/* Size variants (matching codicons) */
.custom-icon.icon-small {
  width: 14px;
  height: 14px;
}

.custom-icon.icon-large {
  width: 20px;
  height: 20px;
}

/* Individual icon masks */
`;

  // Process each SVG file
  for (const file of files) {
    const filePath = path.join(ICONS_DIR, file);
    const svgContent = fs.readFileSync(filePath, "utf-8");
    const dataUri = svgToDataUri(svgContent);
    const className = getIconClassName(file);

    css += `\n.custom-icon.${className} {
  -webkit-mask-image: url('${dataUri}');
  mask-image: url('${dataUri}');
}
`;

    console.log(`✓ Generated .${className}`);
  }

  // Write output file
  fs.writeFileSync(OUTPUT_FILE, css);
  console.log(`\n✅ Generated ${OUTPUT_FILE}`);
  console.log(`   ${files.length} icon class(es) created\n`);

  // Show usage example
  console.log("📖 Usage:");
  console.log('   <i class="custom-icon icon-append"></i>');
  console.log('   <i class="custom-icon icon-append icon-small"></i>');
  console.log();
}

// Run
try {
  generateCustomIcons();
} catch (error) {
  console.error("❌ Error generating custom icons:", error);
  process.exit(1);
}
