#!/usr/bin/env node

/**
 * Generate the named step identity palettes consumed by the dashboard.
 *
 * OKLCH gives the hue ring a more even perceptual spacing than HSL. Chroma is
 * reduced independently per hue until the requested lightness/hue is in the
 * sRGB gamut, then the resulting colors are emitted as reviewable hex values.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const constantsPath = join(rootDir, "src", "types", "DashboardConstants.ts");
const globalsPath = join(
  rootDir,
  "src",
  "ui",
  "webview-react",
  "styles",
  "globals.css"
);

const HUE_COUNT = 8;
const TIER_COUNT = 3;
const BASE_HUE = 0;
const HUE_STEP = 45;
const TIER_HUE_STEP = 15;
const TARGET_CHROMA = 0.18;
const CSS_VARIABLE_COUNT = HUE_COUNT * TIER_COUNT * 2;
const TIERS = {
  dark: [0.78, 0.88, 0.92],
  light: [0.58, 0.54, 0.48],
};

function oklchToLinearSrgb(lightness, chroma, hue) {
  const radians = (hue * Math.PI) / 180;
  const a = chroma * Math.cos(radians);
  const b = chroma * Math.sin(radians);
  const l = lightness + 0.3963377774 * a + 0.2158037573 * b;
  const m = lightness - 0.1055613458 * a - 0.0638541728 * b;
  const s = lightness - 0.0894841775 * a - 1.291485548 * b;
  const l3 = l ** 3;
  const m3 = m ** 3;
  const s3 = s ** 3;

  return [
    4.0767416621 * l3 - 3.3077115913 * m3 + 0.2309699292 * s3,
    -1.2684380046 * l3 + 2.6097574011 * m3 - 0.3413193965 * s3,
    -0.0041960863 * l3 - 0.7034186147 * m3 + 1.707614701 * s3,
  ];
}

function isInSrgbGamut(channels) {
  return channels.every((channel) => channel >= -1e-7 && channel <= 1.0000001);
}

function toSrgb(channel) {
  return channel <= 0.0031308
    ? 12.92 * channel
    : 1.055 * channel ** (1 / 2.4) - 0.055;
}

function oklchToHex(lightness, hue) {
  let low = 0;
  let high = TARGET_CHROMA;
  for (let attempt = 0; attempt < 32; attempt += 1) {
    const chroma = (low + high) / 2;
    if (isInSrgbGamut(oklchToLinearSrgb(lightness, chroma, hue))) {
      low = chroma;
    } else {
      high = chroma;
    }
  }

  const channels = oklchToLinearSrgb(lightness, low, hue).map(toSrgb);
  return `#${channels
    .map((channel) =>
      Math.round(channel * 255)
        .toString(16)
        .padStart(2, "0")
    )
    .join("")}`;
}

function generateTable(tierLightness) {
  return Array.from({ length: HUE_COUNT * TIER_COUNT }, (_, index) => {
    const tier = Math.floor(index / HUE_COUNT);
    const hue =
      BASE_HUE + (index % HUE_COUNT) * HUE_STEP + tier * TIER_HUE_STEP;
    return oklchToHex(tierLightness[tier], hue);
  });
}

const palettes = {
  dark: generateTable(TIERS.dark),
  light: generateTable(TIERS.light),
};

function formatArray(colors, indent = "  ") {
  return colors.map((color) => `${indent}\"${color}\",`).join("\n");
}

function replaceGeneratedConstants(source) {
  const block = `/** Generated by scripts/generate-step-palette.mjs. */
export const STEP_COLOR_PALETTES = {
  rainbow: {
    dark: [
${formatArray(palettes.dark, "      ")}
    ],
    light: [
${formatArray(palettes.light, "      ")}
    ],
  },
} as const;`;
  const pattern =
    /\/\*\* Generated by scripts\/generate-step-palette\.mjs\. \*\/[\s\S]*?\n\n(?=\/\*\*\n \* Stable, curated)/;
  if (!pattern.test(source)) {
    throw new Error(
      "Could not find the generated step palette block in DashboardConstants.ts"
    );
  }
  return source.replace(pattern, `${block}\n\n`);
}

function replaceGeneratedCss(source) {
  // Keep the 48-property surface aligned with the two generated 24-slot
  // tables. The active resolver addresses the first 24 slots; the mirrored
  // second bank keeps the CSS artifact one-to-one with both theme tables.
  const darkProperties = Array.from(
    { length: CSS_VARIABLE_COUNT },
    (_, index) =>
      `  --fp-step-hue-${index}: ${palettes.dark[index % palettes.dark.length]};`
  ).join("\n");
  const lightProperties = Array.from(
    { length: CSS_VARIABLE_COUNT },
    (_, index) =>
      `  --fp-step-hue-${index}: ${palettes.light[index % palettes.light.length]};`
  ).join("\n");
  const block = `/* Generated by scripts/generate-step-palette.mjs. */
:root {
${darkProperties}
}

body.vscode-light,
body.vscode-high-contrast-light {
${lightProperties}
}`;
  const pattern =
    /\/\* Generated by scripts\/generate-step-palette\.mjs\. \*\/[\s\S]*?\n\n(?=\/\* ============================================================================\n   Base Layer)/;
  if (!pattern.test(source)) {
    throw new Error(
      "Could not find the generated step palette block in globals.css"
    );
  }
  return source.replace(pattern, `${block}\n\n`);
}

writeFileSync(
  constantsPath,
  replaceGeneratedConstants(readFileSync(constantsPath, "utf8"))
);
writeFileSync(
  globalsPath,
  replaceGeneratedCss(readFileSync(globalsPath, "utf8"))
);
console.log(
  "Generated rainbow step palettes in DashboardConstants.ts and globals.css"
);
