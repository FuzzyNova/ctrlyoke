#!/usr/bin/env node

/**
 * Generates `syntaxes/ctrlyoke-prompt-markdown.injection.json`: a TextMate
 * injection grammar that colours the text of prompt values in YAML workflow
 * files (`prompt: |`, `retryPrompt: >-`, a plain `prompt: text`) as markdown.
 *
 * The key list is every `PROMPT_TEXT` key of `WORKFLOW_TEXT_FIELDS`
 * (src/completions/WorkflowLocationTypes.ts), so a new prompt field reaches the
 * grammar without a hand edit. That module is TypeScript, so it is bundled in
 * memory with esbuild and imported from the result.
 *
 * Quoted scalars are left to the YAML grammar, and JSON files get no injection
 * because their prompts are escaped strings.
 */

import { build } from "esbuild";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const TEXT_FIELDS_SOURCE = resolve(
  ROOT,
  "src/completions/WorkflowLocationTypes.ts"
);
const OUTPUT_PATH = resolve(
  ROOT,
  "syntaxes/ctrlyoke-prompt-markdown.injection.json"
);
const CHECK_MODE = process.argv.includes("--check");

const SCOPE_NAME = "ctrlyoke.prompt-markdown.injection";
const MARKDOWN_SCOPE = "text.html.markdown";
const BLOCK_CONTENT_NAME =
  "string.unquoted.block.yaml meta.embedded.block.markdown";
const INLINE_CONTENT_NAME =
  "string.unquoted.plain.out.yaml meta.embedded.inline.markdown";

async function loadPromptKeys() {
  const bundled = await build({
    entryPoints: [TEXT_FIELDS_SOURCE],
    bundle: true,
    format: "esm",
    platform: "node",
    write: false,
    logLevel: "silent",
  });
  const source = bundled.outputFiles[0].text;
  const module = await import(
    `data:text/javascript;base64,${Buffer.from(source).toString("base64")}`
  );
  const keys = module.WORKFLOW_TEXT_FIELDS.filter(
    (field) => field.role === "promptText"
  ).map((field) => field.key);
  if (keys.length === 0) {
    throw new Error("WORKFLOW_TEXT_FIELDS has no promptText keys.");
  }
  return [...new Set(keys)].sort();
}

const escapeRegex = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

const IDENT = { name: "punctuation.whitespace.indentation.yaml" };
const PRESENTATION_DETAIL = { include: "source.yaml.1.2#presentation-detail" };

/**
 * The markdown rules shared by every prompt value. Block scalar content has
 * its indentation consumed before these run, so a heading anchors on `\G`
 * (where the YAML grammar's own `while` left off) as well as the line start.
 * The markdown grammar's own heading rule allows only three columns of
 * indentation, which a nested block scalar exceeds.
 */
const MARKDOWN_PATTERNS = [
  { include: "#fenced-code" },
  { include: "#heading" },
  { include: `${MARKDOWN_SCOPE}#inline` },
];

/** One content line rule of the YAML grammar's block scalar, plus markdown. */
const blockContent = (begin, whileRule) => ({
  begin,
  while: whileRule,
  captures: {
    1: IDENT,
    2: IDENT,
    3: { name: "invalid.illegal.expected-indentation.yaml" },
  },
  contentName: BLOCK_CONTENT_NAME,
  patterns: [{ include: "source.yaml#non-printable" }, ...MARKDOWN_PATTERNS],
});

export function buildPromptMarkdownInjection(keys) {
  // The lookbehind is the only place the key is visible, and it consumes
  // nothing, so the YAML grammar still tokenizes the key, the colon and any
  // enclosing sequence item itself and keeps its indentation state.
  // Alternatives are separate because a lookbehind must be fixed width.
  const lookbehind = (suffix) =>
    `(?<=${keys.map((key) => `\\b${escapeRegex(key)}${suffix}`).join("|")})`;
  const afterKey = lookbehind(": ");
  const afterColon = lookbehind(":");
  return {
    $comment:
      "AUTO-GENERATED by scripts/generate-prompt-markdown-injection.mjs from WORKFLOW_TEXT_FIELDS. Do not edit by hand.",
    scopeName: SCOPE_NAME,
    injectionSelector: "L:source.yaml",
    patterns: [
      { include: "#prompt-block-scalar" },
      { include: "#prompt-inline" },
    ],
    repository: {
      // The YAML 1.2 grammar's own `block-scalar` rule (yaml-1.2.tmLanguage.json,
      // the form without an indentation indicator), with the key lookbehind
      // in front and markdown patterns in the content. Its `while` rules end
      // the scalar on exactly the lines YAML's would, which is what keeps the
      // surrounding mapping and sequence state intact.
      "prompt-block-scalar": {
        begin: `${afterKey}(?>(\\|)|(>))([+-]?+)`,
        while: "\\G",
        beginCaptures: {
          1: { name: "keyword.control.flow.block-scalar.literal.yaml" },
          2: { name: "keyword.control.flow.block-scalar.folded.yaml" },
          3: { name: "storage.modifier.chomping-indicator.yaml" },
        },
        name: "meta.scalar.yaml",
        patterns: [
          {
            begin: "$",
            while: "\\G",
            patterns: [
              blockContent("\\G( ++)$", "\\G(?>(\\1)$|(?!\\1)( *+)($|.))"),
              {
                // Matches at most once: its `end` clears the parent `\G`
                // anchor (microsoft/vscode-textmate#114).
                begin: "\\G(?!$)(?=( *+))",
                end: "\\G(?!\\1)(?=[\\t ]*+#)",
                patterns: [
                  blockContent(
                    "\\G( *+)",
                    "\\G(?>(\\1)|( *+)($|[^\\t#]|[\\t ]++[^#]))"
                  ),
                ],
              },
              {
                begin: "(?!\\G)(?=[\\t ]*+#)",
                while: "\\G",
                patterns: [PRESENTATION_DETAIL],
              },
            ],
          },
          { begin: "\\G", end: "$", patterns: [PRESENTATION_DETAIL] },
        ],
      },
      // `prompt: Review **this**`: an unquoted single-line scalar. Quoted
      // values, anchors, tags, flow collections and block headers stay with
      // the YAML grammar.
      "prompt-inline": {
        // Consumes the separating space: the markdown rules mis-scan from a
        // zero-width start. Only whitespace, so the YAML state is unchanged.
        begin: `${afterColon}([ \\t]++)(?![|>"'#&*!\\[{%@\`\\s])`,
        beginCaptures: {
          1: { name: "punctuation.whitespace.separator.yaml" },
        },
        end: "$",
        contentName: INLINE_CONTENT_NAME,
        patterns: [{ include: `${MARKDOWN_SCOPE}#inline` }],
      },
      heading: {
        match: "(?:^|\\G)(#{1,6})(\\s+)(.*?)(\\s+#+\\s*)?$",
        name: "markup.heading.markdown",
        captures: {
          1: { name: "punctuation.definition.heading.markdown" },
          3: { name: "entity.name.section.markdown" },
        },
      },
      "fenced-code": {
        patterns: [{ include: `${MARKDOWN_SCOPE}#fenced_code_block` }],
      },
    },
  };
}

async function main() {
  const content = `${JSON.stringify(buildPromptMarkdownInjection(await loadPromptKeys()), null, 2)}\n`;
  if (CHECK_MODE) {
    if (
      !existsSync(OUTPUT_PATH) ||
      readFileSync(OUTPUT_PATH, "utf8") !== content
    ) {
      console.error(
        "Prompt markdown injection grammar is out of date. Run npm run generate-prompt-markdown-injection."
      );
      process.exitCode = 1;
      return;
    }
    console.log("Prompt markdown injection grammar is up to date.");
    return;
  }
  mkdirSync(dirname(OUTPUT_PATH), { recursive: true });
  writeFileSync(OUTPUT_PATH, content, "utf8");
  console.log(`Written: ${OUTPUT_PATH}`);
}

if (resolve(process.argv[1] ?? "") === fileURLToPath(import.meta.url)) {
  await main();
}
