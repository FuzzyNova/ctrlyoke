import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const themes = [
  {
    source: "dev/reference/vscode-css-vars-defaultdark.json",
    target: "src/server/themes/vscode-default-dark.css",
    editorFont: "'SFMono-Regular', Consolas, 'Liberation Mono', monospace",
  },
  {
    source: "dev/reference/vscode-css-vars-defaultlight.json",
    target: "src/server/themes/vscode-default-light.css",
    editorFont: "'SFMono-Regular', Consolas, 'Liberation Mono', monospace",
  },
];

for (const theme of themes) {
  const snapshot = JSON.parse(
    fs.readFileSync(path.join(root, theme.source), "utf8")
  );
  const vars = snapshot.vars;
  Object.assign(vars, {
    "--vscode-contrastActiveBorder": "transparent",
    "--vscode-editor-findMatchBorder": "transparent",
    "--vscode-toolbar-hoverOutline": "transparent",
    "--vscode-contrastBorder": "transparent",
    "--vscode-editor-findMatchHighlightBorder": "transparent",
    "--vscode-editor-selectionForeground": vars["--vscode-editor-foreground"],
    "--vscode-editor-selectionHighlightBorder": "transparent",
    "--vscode-terminal-background": vars["--vscode-editor-background"],
  });
  vars["--vscode-font-family"] =
    "-apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif";
  vars["--vscode-editor-font-family"] = theme.editorFont;
  vars["--vscode-codicon-font-path"] = 'url("/codicons/codicon.ttf")';
  const css = `/* Generated by npm run generate-server-themes. */\n:root {\n${Object.entries(
    vars
  )
    .map(([name, value]) => `  ${name}: ${value};`)
    .join("\n")}\n}\n`;
  const targetPath = path.join(root, theme.target);
  fs.mkdirSync(path.dirname(targetPath), { recursive: true });
  fs.writeFileSync(targetPath, css);
}
